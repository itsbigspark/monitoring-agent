#!/usr/bin/env node
// Generates Kiro spec adapter files from canonical specs at <specsDir>/<id>/.
// Each adapter is a header comment + a one-liner `#[[file:...]]` import, so
// Kiro's native spec UX drives against canonical content with zero
// duplication.
//
// Direction is ONE-WAY by construction: sync writes only under the .kiro
// spec root and never touches <specsDir> — adapters are pure imports and
// cannot carry state (status, owner) back to the source. The sole
// adapter→source path is the explicit `--promote` flag. If canonical
// frontmatter ever regresses (e.g. a Done ticket flipping back), the writer
// is something else — a stale runtime writing through the resolved import,
// a lost working-tree edit — and the `status:check` gate
// (check-status-regression.mjs, issue #78) is the defense.
//
// Usage:
//   node tools/qa/sync-kiro-specs.mjs                        # write adapters; remove orphan adapters
//   node tools/qa/sync-kiro-specs.mjs --check                # exit non-zero on any drift OR Kiro-native content
//   node tools/qa/sync-kiro-specs.mjs --promote <id>         # move Kiro-native files to canonical, then sync
//   node tools/qa/sync-kiro-specs.mjs --promote <id> --force # also promote when canonical already exists
//   node tools/qa/sync-kiro-specs.mjs --promote-all --force  # bulk auto-promote every spec id with Kiro-native content
//
// Behaviour mirrors the canonical the-one tool: refuses to overwrite
// Kiro-native content; promotes Kiro IDE writes to canonical on demand.

import { execSync } from "node:child_process";
import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  renameSync,
  rmSync,
  writeFileSync
} from "node:fs";
import { join } from "node:path";
import { HARNESS_PATHS } from "./harness-paths.mjs";

const CONFIG_FILE = HARNESS_PATHS.config;
const SPEC_ID_PATTERN = /^[a-z0-9](?:[a-z0-9]|-(?=[a-z0-9]))*$/;
const TEMPLATE_DIR = "_template";
const SPEC_FILES = ["requirements.md", "design.md", "tasks.md"];
const ADAPTER_HEADER = "<!-- AUTO-GENERATED by tools/qa/sync-kiro-specs.mjs — do not edit. -->";

function readConfig() {
  if (!existsSync(CONFIG_FILE)) {
    console.error(`sync-kiro-specs: missing ${CONFIG_FILE}`);
    process.exit(1);
  }
  const config = JSON.parse(readFileSync(CONFIG_FILE, "utf8"));
  if (!config.workflow?.specsDir) {
    console.error("sync-kiro-specs: workflow.specsDir not configured in manifest");
    process.exit(1);
  }
  if (!config.kiro?.specFolders?.enabled) {
    console.error("sync-kiro-specs: kiro.specFolders.enabled is false in manifest");
    process.exit(1);
  }
  return {
    specRoot: config.workflow.specsDir,
    kiroSpecRoot: config.kiro.specFolders.root || HARNESS_PATHS.kiroSpecsDefault
  };
}

function adapterContent(specRoot, specDir, fileName) {
  return [ADAPTER_HEADER, `#[[file:${specRoot}/${specDir}/${fileName}]]`, ""].join("\n");
}

function isAdapter(text, specRoot) {
  if (!text.startsWith(ADAPTER_HEADER)) return false;
  const escaped = specRoot.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const re = new RegExp(`#\\[\\[file:${escaped}\\/[^/]+\\/[^\\]]+\\.md\\]\\]`);
  return re.test(text);
}

function listSpecDirs(root) {
  if (!existsSync(root)) return [];
  return readdirSync(root, { withFileTypes: true })
    .filter((d) => d.isDirectory() && d.name !== TEMPLATE_DIR)
    .map((d) => d.name);
}

function listFiles(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true })
    .filter((d) => d.isFile())
    .map((d) => d.name);
}

function plan(config) {
  const { specRoot, kiroSpecRoot } = config;
  const canonical = listSpecDirs(specRoot);
  const kiroDirs = listSpecDirs(kiroSpecRoot);
  const canonicalSet = new Set(canonical);

  const writes = [];
  const orphanFileDeletes = [];
  const blocked = [];

  for (const dir of canonical) {
    for (const fileName of SPEC_FILES) {
      const canonicalPath = join(specRoot, dir, fileName);
      const adapterPath = join(kiroSpecRoot, dir, fileName);
      const canonicalExists = existsSync(canonicalPath);
      const adapterExists = existsSync(adapterPath);

      if (canonicalExists) {
        if (adapterExists) {
          const text = readFileSync(adapterPath, "utf8");
          if (!isAdapter(text, specRoot)) {
            blocked.push({
              dir,
              files: [fileName],
              reason: `Kiro-native ${fileName} at ${kiroSpecRoot}/${dir}/ would be overwritten by adapter regeneration. Promote: npm run kiro:promote ${dir} -- --force OR discard: git checkout ${kiroSpecRoot}/${dir}/${fileName}`
            });
            continue;
          }
        }
        writes.push({ path: adapterPath, content: adapterContent(specRoot, dir, fileName) });
      } else if (adapterExists) {
        const text = readFileSync(adapterPath, "utf8");
        if (isAdapter(text, specRoot) || text.trim().length === 0) {
          orphanFileDeletes.push(adapterPath);
        } else {
          blocked.push({
            dir,
            files: [fileName],
            reason: `Kiro-native ${fileName} exists at ${kiroSpecRoot}/${dir}/ but no canonical at ${specRoot}/${dir}/${fileName}. Promote: npm run kiro:promote ${dir}`
          });
        }
      }
    }
  }

  for (const dir of kiroDirs) {
    if (canonicalSet.has(dir)) continue;
    const files = listFiles(join(kiroSpecRoot, dir));
    const nonAdapterFiles = [];
    const adapterFiles = [];
    for (const fileName of files) {
      const text = readFileSync(join(kiroSpecRoot, dir, fileName), "utf8");
      if (isAdapter(text, specRoot) || text.trim().length === 0) adapterFiles.push(fileName);
      else nonAdapterFiles.push(fileName);
    }
    if (nonAdapterFiles.length > 0) {
      blocked.push({
        dir,
        files: nonAdapterFiles,
        reason: `Kiro-native spec at ${kiroSpecRoot}/${dir}/ has no canonical at ${specRoot}/${dir}/`
      });
    } else {
      for (const fileName of adapterFiles) {
        orphanFileDeletes.push(join(kiroSpecRoot, dir, fileName));
      }
    }
  }

  return { writes, orphanFileDeletes, blocked };
}

function applyPlan(config, { writes, orphanFileDeletes }) {
  for (const path of orphanFileDeletes) {
    if (!existsSync(path)) continue;
    rmSync(path, { force: true });
  }
  for (const dir of listSpecDirs(config.kiroSpecRoot)) {
    const dirPath = join(config.kiroSpecRoot, dir);
    if (listFiles(dirPath).length === 0) rmSync(dirPath, { recursive: true, force: true });
  }
  for (const { path, content } of writes) {
    const dir = path.split("/").slice(0, -1).join("/");
    mkdirSync(dir, { recursive: true });
    writeFileSync(path, content);
  }
}

function blockedMessage(config, blocked) {
  const lines = ["Kiro-native spec content found that has no canonical equivalent:"];
  for (const b of blocked) {
    lines.push(`  - ${config.kiroSpecRoot}/${b.dir}/  (${b.files.join(", ")})`);
    lines.push(`      ${b.reason}`);
  }
  return lines.join("\n");
}

function checkPlan({ writes, orphanFileDeletes, blocked }) {
  const drift = [];
  for (const { path, content } of writes) {
    if (!existsSync(path)) {
      drift.push(`missing adapter: ${path}`);
      continue;
    }
    const onDisk = readFileSync(path, "utf8");
    if (onDisk !== content) drift.push(`drifted adapter: ${path}`);
  }
  for (const path of orphanFileDeletes) {
    drift.push(`orphan adapter to remove: ${path}`);
  }
  return { drift, blocked };
}

function promote(config, id, force) {
  if (!SPEC_ID_PATTERN.test(id)) {
    console.error(
      `promote: invalid id "${id}". Spec ids are lowercase kebab-case.`
    );
    process.exit(1);
  }
  const kiroDir = join(config.kiroSpecRoot, id);
  const canonicalDir = join(config.specRoot, id);
  if (!existsSync(kiroDir)) {
    console.error(`promote: ${kiroDir} does not exist`);
    process.exit(1);
  }
  const filesToPromote = [];
  for (const fileName of listFiles(kiroDir)) {
    if (!fileName.endsWith(".md")) continue;
    const text = readFileSync(join(kiroDir, fileName), "utf8");
    if (text.trim().length === 0) {
      console.error(
        `promote: ${join(kiroDir, fileName)} is empty — Kiro placeholder, no content to promote.`
      );
      console.error("Generate content in Kiro first, or delete the placeholder file.");
      process.exit(1);
    }
    if (!isAdapter(text, config.specRoot)) filesToPromote.push(fileName);
  }
  if (filesToPromote.length === 0) {
    console.error(`promote: no Kiro-native .md files in ${kiroDir} (only adapters present)`);
    process.exit(1);
  }
  for (const fileName of filesToPromote) {
    if (existsSync(join(canonicalDir, fileName))) {
      if (!force) {
        console.error(
          `promote: refusing to overwrite ${join(canonicalDir, fileName)}. Re-run with --force to replace.`
        );
        process.exit(1);
      }
    }
  }
  mkdirSync(canonicalDir, { recursive: true });
  for (const fileName of filesToPromote) {
    const target = join(canonicalDir, fileName);
    const wasOverwrite = existsSync(target);
    renameSync(join(kiroDir, fileName), target);
    console.log(
      `promoted ${join(kiroDir, fileName)} → ${target}${wasOverwrite ? " (replaced)" : ""}`
    );
  }
  applyPlan(config, plan(config));
  if (existsSync("tools/qa/generate-backlog.mjs")) {
    execSync("node tools/qa/generate-backlog.mjs", { stdio: "inherit" });
  }
  console.log(`promote: ${id} promoted; adapters regenerated.`);
}

function promoteAll(config, force) {
  const ids = listSpecDirs(config.kiroSpecRoot);
  const dirty = [];
  for (const id of ids) {
    const dirPath = join(config.kiroSpecRoot, id);
    for (const fileName of listFiles(dirPath)) {
      if (!fileName.endsWith(".md")) continue;
      const text = readFileSync(join(dirPath, fileName), "utf8");
      if (text.trim().length === 0) continue;
      if (isAdapter(text, config.specRoot)) continue;
      dirty.push(id);
      break;
    }
  }
  if (dirty.length === 0) {
    console.log("promote-all: no Kiro-native spec content to promote.");
    return;
  }
  for (const id of dirty) {
    promote(config, id, force);
  }
  console.log(`promote-all: promoted ${dirty.length} spec id(s).`);
}

function main() {
  const config = readConfig();
  if (!existsSync(config.specRoot)) {
    console.error(`${config.specRoot} missing — nothing to sync`);
    process.exit(1);
  }
  if (!existsSync(config.kiroSpecRoot)) {
    mkdirSync(config.kiroSpecRoot, { recursive: true });
  }

  if (process.argv.includes("--promote-all")) {
    const force = process.argv.includes("--force");
    promoteAll(config, force);
    return;
  }

  const promoteIdx = process.argv.indexOf("--promote");
  if (promoteIdx >= 0) {
    const id = process.argv[promoteIdx + 1];
    if (!id || id.startsWith("--")) {
      console.error("promote: usage: npm run kiro:promote <spec-id> [-- --force]");
      process.exit(1);
    }
    const force = process.argv.includes("--force");
    promote(config, id, force);
    return;
  }

  const checkMode = process.argv.includes("--check");
  const p = plan(config);

  if (checkMode) {
    const { drift, blocked } = checkPlan(p);
    if (blocked.length > 0) {
      console.error(blockedMessage(config, blocked));
      process.exit(1);
    }
    if (drift.length > 0) {
      console.error("kiro:check failed — run 'npm run kiro:sync':");
      for (const d of drift) console.error(`  - ${d}`);
      process.exit(1);
    }
    console.log("kiro:check passed");
    return;
  }

  if (p.blocked.length > 0) {
    console.error(blockedMessage(config, p.blocked));
    console.error("kiro:sync refused to proceed. Promote Kiro-native specs first.");
    process.exit(1);
  }
  applyPlan(config, p);
  console.log(
    `kiro:sync wrote ${p.writes.length} adapter(s), removed ${p.orphanFileDeletes.length} orphan adapter(s)`
  );
}

main();
